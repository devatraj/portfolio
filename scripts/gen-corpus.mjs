// Builds src/lib/corpus.gen.js from profile.yaml, so the browser and the Pages Function
// answer from exactly the same facts. Runs before every dev and build.
import { readFileSync, writeFileSync } from 'node:fs';
import { load } from 'js-yaml';
import { buildCorpus } from '../src/lib/ask-core.js';

const profile = load(readFileSync(new URL('../src/data/profile.yaml', import.meta.url), 'utf8'));
const corpus = buildCorpus(profile);
writeFileSync(
  new URL('../src/lib/corpus.gen.js', import.meta.url),
  `// Generated by scripts/gen-corpus.mjs from profile.yaml. Do not edit.\nexport default ${JSON.stringify(corpus, null, 1)};\n`,
);
console.log(`corpus: ${corpus.length} entries`);
